#pragma once

/**
 * @file ErrorKind.h
 * @brief Категория ошибки, пришедшей от сетевого слоя или протокола.
 *
 * Разные категории требуют разной реакции:
 *   - Transport: соединение потеряно или не установлено — попробовать переподключиться.
 *   - Protocol:  нарушение формата пакета — вероятно, баг или несовместимость версий.
 *   - Business:  операция отклонена сервером (неверный пароль, чат не создан и т.п.).
 */
enum class ErrorKind
{
    Transport,
    Protocol,
    Business
};
