/**
 * @file    PortSelector.h
 * @brief   Утилиты для проверки и интерактивного выбора TCP-порта.
 *
 * @details
 *     - tryCreateSocketOnPort — быстрая проверка «занят ли порт» через
 *       попытку bind на временном сокете;
 *     - getValidPort — интерактивный диалог с пользователем,
 *       возвращает гарантированно свободный порт или сигнал остановки.
 *
 * @note    getValidPort блокирует поток до ввода пользователя или
 *          до прихода SIGINT/SIGTERM.
 * @see     ServerConfig, ShutdownSignal, ListeningSocket
 */

#pragma once

/**
 * @brief Проверяет, свободен ли TCP-порт.
 *
 * @param port Номер порта (1..65535).
 *
 * @return true  — порт свободен, bind прошёл успешно;
 *         false — порт занят, либо не удалось создать временный
 *                 сокет (нехватка fd, нет прав и т.п.).
 *
 * @details
 *   Создаёт временный TCP-сокет, ставит SO_REUSEADDR (чтобы проверка
 *   не спотыкалась о TIME_WAIT от предыдущего запуска сервера),
 *   пытается сделать bind на INADDR_ANY:port. Результат bind —
 *   ответ. Сокет закрывается в любом случае.
 *
 */
bool tryCreateSocketOnPort(int port);

/**
 * @brief Интерактивно запрашивает у пользователя свободный порт.
 *
 * @param defaultPort Порт, предлагаемый по умолчанию (при пустом вводе).
 *
 * @return Гарантированно свободный порт (1..65535),
 *         либо -1, если во время диалога пришёл SIGINT/SIGTERM.
 *
 * @details
 *   Цикл:
 *     1. Печатает приглашение.
 *     2. Читает строку через std::getline.
 *     3. Пустая строка — проверяет defaultPort; если свободен,
 *        возвращает его.
 *     4. Иначе std::stoi + проверка диапазона 1..65535,
 *        затем tryCreateSocketOnPort.
 *     5. При любой неудаче — повторяет ввод.
 *
 *   При некорректном числе (std::invalid_argument,
 *   std::out_of_range) пишет ошибку в лог и просит ввести снова.
 */
int getValidPort(int defaultPort);
